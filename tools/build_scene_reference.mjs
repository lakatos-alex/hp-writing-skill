/** Build a selective manual view of the same evidence cards used by hp.mjs. */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const skill=path.join(root,'skills/harry-potter-fanfic');
const facts=JSON.parse(fs.readFileSync(path.join(skill,'data/facts.json'),'utf8'));
const sections={
  'Physical limits and supplies':['first-camp-injury','first-camp-provisions','food-exception'],
  'Objects and information routes':['mirror-desire','map-geographic-scope','beaded-bag-storage','deluminator-discovery','protean-coins','neville-wrapper'],
  'Knowledge, testimony and trust':['diary-coercion','trace-misattribution','prince-spell-authorship','altered-memory','grimmauld-refuge-risk','taboo-disclosure'],
  'Learned competence and obligations':['unlocking-has-limits','patronus-training','non-verbal-casting-evidence','tournament-contract','dobby-wages']
};
let output='# Selected canon constraints for writing\n\n'+
  'A selective manual view of the shared [evidence cards](../data/facts.json), across all seven novels. '+
  'Read only the entries that affect this scene. These are constraints, not story beats or a complete scene database; '+
  'the writer decides what people do about them. Chapter anchors locate evidence, not automatic character knowledge. '+
  'Keep an event, an attributed claim and an interpretation distinct. If a consequential fact is absent, '+
  'check the [public inventories](book-dossiers.md#typed-inventory-navigation) or local primary context; absence from this selection is not canon absence.\n\n'+
  'Before drafting, establish only two to four consequential facts: physical capacity, actual supplies, '+
  'object capability and the information available at this date. During revision, check those facts against '+
  'the written actions. Avoid turning the prose into a factual briefing. A mistaken proposal may be rejected '+
  'by another character; narration should not silently endorse it.\n\n';
for(const [heading,ids] of Object.entries(sections)){
  output+=`## ${heading}\n\n`;
  for(const id of ids){
    const f=facts.find(f=>f.id===id);if(!f)throw Error(`Missing selected fact: ${id}`);
    output+=`- **${f.id} — ${f.anchors.join(', ')} (${f.kind}).** ${f.claim} ${f.limits}\n\n`;
  }
}
output+='## Evidence and upkeep\n\nThis view is generated by the contributor tool `tools/build_scene_reference.mjs`; '+
  'the installed reference has no runtime requirement. Claims and limits live in `data/facts.json`, '+
  'which also retains evidence locators and source-quality notes. All seven books are represented, '+
  'but selected constraints and independent reading remain incomplete. Hungarian DH transcription is degraded; '+
  'its locators are not spelling or anatomical authority. The ordinary status of a possession survives storage in an enchanted bag.\n';
const file=path.join(skill,'references/selected-canon-constraints.md');
if(process.argv.includes('--check')){
  if(!fs.existsSync(file)||fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n')!==output)throw Error('Selected canon reference is stale; rebuild it.');
  console.log('PASS: selected canon reference matches shared evidence cards.');
}else{fs.writeFileSync(file,output);console.log('Built selected canon constraints from 20 shared evidence cards.');}
